function makeLocation(params: {
  id: string;
  reportId: string;
  issueId: string | null;
  lat: number | null;
  lng: number | null;
  accuracy: number | null;
  source: LocationObservation['location_source'];
  meaning: LocationObservation['location_meaning'];
  label: string;
  recordedAt: string;
  confirmed: boolean;
  verified: boolean;
}): LocationObservation {
  const jurisdiction = checkTumakuruPlausibility(params.lat, params.lng);
  return {
    location_observation_id: params.id,
    report_id: params.reportId,
    physical_issue_id: params.issueId,
    latitude: params.lat,
    longitude: params.lng,
    horizontal_accuracy_meters: params.accuracy,
    coordinate_reference_system: 'EPSG:4326',
    location_source: params.source,
    location_meaning: params.meaning,
    human_readable_label: params.label,
    captured_at: params.recordedAt,
    recorded_at: params.recordedAt,
    confirmed_by_user: params.confirmed,
    verified_by_authorized_reviewer: params.verified,
    validation_status: deriveLocationValidationStatus({
      latitude: params.lat,
      longitude: params.lng,
      accuracyMeters: params.accuracy,
      jurisdictionStatus: jurisdiction,
    }),
    precision_band: classifyGpsPrecisionBand(params.accuracy),
    jurisdiction_status: jurisdiction,
    supersedes_location_observation_id: null,
  };
}

